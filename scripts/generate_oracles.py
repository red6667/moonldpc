"""Independent, deterministic test oracles; Python 3.8+ standard library only.

SPA check messages are computed by enumerating parity-constrained assignments,
not the production prefix/suffix box-plus algorithm. Min-sum enumerates all
other neighbors separately. No third-party decoder source or fixtures are used.
Run --check to detect generated fixture drift without changing files.
"""
import argparse
import itertools
import math
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]


def syndrome(rows, word):
    return [sum(word[v] for v in row) % 2 for row in rows]


def check_message(others, algorithm, alpha, offset, bound):
    if not others:
        return bound
    if algorithm == 'SumProduct':
        masses = [0.0, 0.0]
        for assignment in itertools.product((0, 1), repeat=len(others)):
            masses[sum(assignment) % 2] += math.exp(-sum(a * b for a, b in zip(assignment, others)))
        value = math.log(masses[0]) - math.log(masses[1])
    else:
        sign = -1 if sum(x < 0 for x in others) % 2 else 1
        value = sign * alpha * max(0, min(abs(x) for x in others) - offset)
    return max(-bound, min(bound, value))


def decode(n, rows, channel, algorithm, iterations, alpha, offset, bound):
    clip = lambda x: max(-bound, min(bound, x))
    channel = list(map(clip, channel))
    posterior = channel[:]
    old = {(c, v): 0.0 for c, row in enumerate(rows) for v in row}
    incoming = {(c, v): channel[v] for c, row in enumerate(rows) for v in row}
    weight = lambda: sum(syndrome(rows, [int(x < 0) for x in posterior]))
    history = [weight()]
    for _ in range(iterations):
        if history[-1] == 0:
            break
        if algorithm == 'LayeredMinSum':
            for c, row in enumerate(rows):
                values = {v: clip(posterior[v] - old[c, v]) for v in row}
                fresh = {v: check_message([values[u] for u in row if u != v], algorithm, alpha, offset, bound) for v in row}
                for v in row:
                    posterior[v] += fresh[v] - old[c, v]
                    old[c, v] = fresh[v]
        else:
            fresh = {(c, v): check_message([incoming[c, u] for u in row if u != v], algorithm, alpha, offset, bound)
                     for c, row in enumerate(rows) for v in row}
            posterior = [channel[v] + sum(fresh[c, v] for c, row in enumerate(rows) if v in row) for v in range(n)]
            incoming = {(c, v): clip(posterior[v] - fresh[c, v]) for c, row in enumerate(rows) for v in row}
        history.append(weight())
    return list(map(clip, posterior)), history


def literal(value):
    if isinstance(value, list):
        return '[' + ', '.join(map(literal, value)) + ']'
    if isinstance(value, float):
        return repr(value)
    return str(value)


def generate():
    rng = random.Random(20261021)
    out = ['// Generated by scripts/generate_oracles.py; tests only, excluded from production LOC.']
    for algorithm in ['SumProduct', 'MinSum', 'LayeredMinSum']:
        out.append('///|\ntest "independent %s assignment oracle: 48 deterministic graphs" {' % algorithm)
        for case in range(48):
            n = rng.randrange(2, 8)
            rows = [sorted(rng.sample(range(n), rng.randrange(0, min(n, 5) + 1))) for _ in range(rng.randrange(1, 6))]
            channel = [rng.choice([-12.0, -4.1, -0.7, 0.0, 0.3, 1.9, 12.0]) for _ in range(n)]
            alpha = 1.0 if algorithm == 'SumProduct' else rng.choice([1.0, 0.8])
            offset = 0.0 if algorithm == 'SumProduct' else rng.choice([0.0, 0.25])
            iterations = case % 6
            posterior, history = decode(n, rows, channel, algorithm, iterations, alpha, offset, 8.0)
            out.append('  oracle_decode(%d, %s, %s, @moonldpc.%s, %d, %s, %s, %s, %s)' % (n, literal(rows), literal(channel), algorithm, iterations, alpha, offset, literal(posterior), literal(history)))
        out.append('}')
    out.append('///|\ntest "independent brute force kernel oracle: 40 matrices" {')
    for _ in range(40):
        n = rng.randrange(1, 9)
        rows = [sorted(rng.sample(range(n), rng.randrange(n + 1))) for _ in range(rng.randrange(1, 7))]
        valid = [mask for mask in range(1 << n) if not any(syndrome(rows, [(mask >> v) & 1 for v in range(n)]))]
        out.append('  oracle_kernel(%d, %s, %s)' % (n, literal(rows), literal(valid)))
    out.append('}')
    out.append('///|\ntest "exact star-tree posterior from full codeword marginalization: 20 cases" {')
    for case in range(20):
        n = 2 + case % 5
        channel = [rng.uniform(0.2, 2.5) * (-1 if v == 0 else 1) for v in range(n)]
        words = [list(word) for word in itertools.product((0, 1), repeat=n) if sum(word) % 2 == 0]
        weights = [math.exp(-sum(x * b for x, b in zip(channel, word))) for word in words]
        posterior = [math.log(sum(w for w, word in zip(weights, words) if word[v] == 0)) - math.log(sum(w for w, word in zip(weights, words) if word[v] == 1)) for v in range(n)]
        out.append('  oracle_decode(%d, [%s], %s, @moonldpc.SumProduct, 1, 1.0, 0.0, %s, %s)' % (n, literal(list(range(n))), literal(channel), literal(posterior), literal([1, sum(syndrome([list(range(n))], [int(x < 0) for x in posterior]))])))
    out.append('}')
    return '\n'.join(out) + '\n'


def compare_fixtures(actual, expected):
    """Keep structure/integers exact; tolerate libm's last floating-point ulps.

    The MoonBit numeric oracle asserts 1e-9; regeneration is stricter at 1e-12.
    Windows/Python 3.8 and Linux/Python may print different last binary64 ulps.
    """
    import re
    normalize = lambda s: re.sub(r'\s+', '', s).replace(',)', ')').replace(',]', ']')
    number = re.compile(r'(?<![A-Za-z_0-9])[-+]?\d+\.\d+(?:[eE][-+]?\d+)?')
    actual, expected = normalize(actual), normalize(expected)
    actual_values, expected_values = number.findall(actual), number.findall(expected)
    if number.sub('<FLOAT>', actual) != number.sub('<FLOAT>', expected):
        return 'non-floating fixture structure changed'
    if len(actual_values) != len(expected_values):
        return 'floating fixture count changed'
    for index, (a, b) in enumerate(zip(actual_values, expected_values)):
        if not math.isclose(float(a), float(b), rel_tol=1e-12, abs_tol=1e-12):
            return 'floating fixture %d drifted: actual=%s expected=%s' % (index, a, b)
    return None


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'oracle_test.mbt'
    content = generate()
    # Formatting is allowed to reflow generated MoonBit; the raw fixture is kept
    # separately for reproducibility by comparing normalized non-whitespace tokens.
    if args.check:
        error = compare_fixtures(path.read_text(encoding='utf-8-sig'), content)
        if error:
            raise SystemExit('oracle fixture drift: ' + error)
        print('oracle fixtures verified: 144 iterative cases, 40 kernels, 20 exact marginals')
    else:
        path.write_text(content, encoding='utf-8')
        print('generated independent oracle fixtures')
